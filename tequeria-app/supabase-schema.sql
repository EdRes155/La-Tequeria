-- ---------------------------------------------------------------------
--  CATÁLOGO INICIAL: carnes, bebidas, mesas y precios con los que empieza una sucursal. Es el único
--  lugar donde se define: lo usan la primera instalación (aquí abajo) y cada sucursal nueva que se crea
